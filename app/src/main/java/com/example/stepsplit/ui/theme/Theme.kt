/**
 * Always the app's own green scheme, never Android 12+'s wallpaper-based dynamic colors: the step
 * chart's fixed workout/incidental greens ([WorkoutSegmentColor], [IncidentalSegmentColor]) and the
 * trip map's start marker only match the rest of the screen in this scheme.
 */
@Composable
fun StepSplitTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = StepSplitTypography,
        content = content,
    )
}
